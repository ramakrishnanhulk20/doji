"""Turns the kanji of the six Osaka merchant ranks into SVG paths.

Seal kanji are paths, never live text, so a seal renders the same in every browser and in share images.
Usage (the TTF is not committed; fetch it from github.com/google/fonts, ofl/shipporiminchob1):

    pip install fonttools
    python scripts/build-seal-paths.py path/to/ShipporiMinchoB1-ExtraBold.ttf

Each path is moved so the ink box starts at (0, 0) and the y axis is flipped (fonts point up, SVG points down).
width and height are the ink box, so a seal can fit a kanji into a box with one scale.
"""

import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

CHARACTERS = "丁稚手代番頭仲買両替商相場師"
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "components" / "ledger" / "seal-paths.ts"


def glyph_entry(font: TTFont, char: str) -> tuple[str, float, float]:
    glyphs = font.getGlyphSet()
    name = font.getBestCmap()[ord(char)]

    bounds = BoundsPen(glyphs)
    glyphs[name].draw(bounds)
    x_min, y_min, x_max, y_max = bounds.bounds

    # Flip the y axis and slide the ink box to the origin in one matrix.
    svg = SVGPathPen(glyphs, ntos=lambda value: f"{value:.1f}".rstrip("0").rstrip("."))
    glyphs[name].draw(TransformPen(svg, (1, 0, 0, -1, -x_min, y_max)))
    return svg.getCommands(), x_max - x_min, y_max - y_min


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: python scripts/build-seal-paths.py path/to/ShipporiMinchoB1-ExtraBold.ttf")

    font = TTFont(sys.argv[1])
    lines = [
        "// Generated by scripts/build-seal-paths.py from Shippori Mincho B1 ExtraBold (SIL OFL). Do not edit by hand.",
        "// Each path has its ink box at (0, 0), the y axis flipped, and width and height of that box.",
        "",
        "export type KanjiPath = { d: string; width: number; height: number };",
        "",
        "export const SEAL_PATHS: Record<string, KanjiPath> = {",
    ]
    for char in CHARACTERS:
        d, width, height = glyph_entry(font, char)
        lines.append(f'  "{char}": {{ d: "{d}", width: {width:.1f}, height: {height:.1f} }},')
    lines.append("};")
    lines.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes, {len(CHARACTERS)} characters)")


if __name__ == "__main__":
    main()
